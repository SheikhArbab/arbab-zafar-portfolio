/**
 * Generates supabase/seed.sql from src/content/defaults.ts.
 * Run: npm run seed:generate   (Node ≥ 22.18 runs .ts natively)
 * The seed uses ON CONFLICT DO NOTHING, so re-running never overwrites admin edits.
 */
import { writeFileSync } from 'node:fs'
import { defaultData, defaultProjects } from '../src/content/defaults.ts'

type V = string | number | boolean | null | undefined | string[] | object

const lit = (v: V): string => {
  if (v === null || v === undefined) return 'null'
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (typeof v === 'number') return String(v)
  if (typeof v === 'string') return `'${v.replace(/'/g, "''")}'`
  if (Array.isArray(v) && v.every((x) => typeof x === 'string')) {
    return v.length ? `array[${v.map(lit).join(', ')}]::text[]` : `'{}'::text[]`
  }
  return `${lit(JSON.stringify(v))}::jsonb`
}

function insert(table: string, rows: Record<string, unknown>[], conflict = 'id') {
  if (!rows.length) return `-- ${table}: no seed rows\n`
  const cols = Object.keys(rows[0])
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c] as V)).join(', ')})`).join(',\n')
  return `insert into public.${table} (${cols.join(', ')}) values\n${values}\non conflict (${conflict}) do nothing;\n`
}

const { profile, settings, categories, skills, experiences } = defaultData
const projects = defaultProjects // includes unpublished drafts
const omit = <T extends object>(o: T, keys: string[]) => Object.fromEntries(Object.entries(o).filter(([k]) => !keys.includes(k)))

const sql = [
  '-- AUTO-GENERATED by scripts/generate-seed.ts. Do not edit by hand.',
  '-- Initial content (from the previous portfolio + profile brief). Edit everything later in /admin.',
  '',
  insert('profile', [omit(profile, ['updated_at'])]),
  insert('site_settings', [omit(settings, ['updated_at'])]),
  insert('skill_categories', categories.map((c) => omit(c, ['updated_at']))),
  insert('skills', skills.map((s) => omit(s, ['updated_at']))),
  insert('experiences', experiences.map((e) => omit(e, ['updated_at', 'created_at']))),
  insert('projects', projects.map((p) => omit(p, ['project_images', 'updated_at', 'created_at']))),
  // Admin-only (RLS): where new contact-form messages are emailed. Kept out of src/ so it never reaches the browser bundle.
  insert('private_settings', [{ id: 1, notify_email: 'arbabzafar4444@gmail.com', notify_enabled: true }]),
].join('\n')

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log('✓ wrote supabase/seed.sql')
