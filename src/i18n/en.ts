type Widen<T> = T extends (...args: infer A) => infer R
  ? (...args: A) => R
  : T extends readonly [infer _A, ...infer _B]
    ? { [K in keyof T]: Widen<T[K]> }
    : T extends object
      ? { [K in keyof T]: Widen<T[K]> }
      : T extends string
        ? string
        : T

